//! sRGB transfer function as exact tables, generated once from the piecewise sRGB curve in
//! double precision and rounded to f32 (stored as bit patterns, so no literal rounding).
//! Deterministic on every platform and faster than evaluating `powf` per channel.
//! Generator: ADR 0011, appendix.

/// Reads a table of f32 bit patterns as f32 values.
const fn floats<const N: usize>(bits: [u32; N]) -> [f32; N] {
    let mut out = [0.0; N];
    let mut i = 0;
    while i < N {
        out[i] = f32::from_bits(bits[i]);
        i += 1;
    }
    out
}

